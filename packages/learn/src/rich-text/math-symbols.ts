const DOUBLE_STRUCK = new Map([
  ["C", "ℂ"],
  ["N", "ℕ"],
  ["Q", "ℚ"],
  ["R", "ℝ"],
  ["Z", "ℤ"],
]);

export function toDoubleStruck(letters: string): string {
  return letters.replaceAll(/[CNQRZ]/gu, (letter) => DOUBLE_STRUCK.get(letter) ?? letter);
}

