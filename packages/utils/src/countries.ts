const COUNTRY_CODES: readonly string[] = Object.keys(CONTENT_CURRENCIES);

export type CountryChoice = { code: string; name: string };

export function isCountryCode(code: string): boolean {
  return Object.hasOwn(CONTENT_CURRENCIES, code);
}

/**
 * The country content in this language is written for when nothing names another: the one whose
 * flag the language shows, the same country its lessons' variety comes from. Null for a language
 * the app doesn't write content in.
 */
export function getLanguageCountry(language: string): string | null {
  const locale = getContentLocale(language);
  const flag = locale ? getLanguageFlagCode(locale) : null;
  return flag ? flag.toUpperCase() : null;
}

export function getContentCurrency(country: string): string | null {
  return isCountryCode(country) ? (CONTENT_CURRENCIES[country] ?? null) : null;
}

/** `first` codes lead in their order; the rest follow by name in the learner's language. */
export function getCountryChoices({
  first = [],
  userLanguage,
}: {
  first?: readonly string[];
  userLanguage: string;
}): CountryChoice[] {
  const names = new Intl.DisplayNames([userLanguage], { type: "region" });
  const collator = new Intl.Collator(userLanguage);
  const leading = [...new Set(first)].filter((code) => isCountryCode(code));
  const toChoice = (code: string) => ({ code, name: names.of(code) ?? code });

  const rest = COUNTRY_CODES.filter((code) => !leading.includes(code))
    .map((code) => toChoice(code))
    .toSorted((a, b) => collator.compare(a.name, b.name));

  return [...leading.map((code) => toChoice(code)), ...rest];
}
