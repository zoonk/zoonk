"""Copies Main's server-rendered stats components into client copies (buddy-main-*.tsx) the renderer can load.

Only mechanical rewrites: async components become hook components (getExtracted -> useExtracted,
getFormatter -> useFormatter), and imports become absolute repo paths or the other copies.
init.mjs runs it; run it again after those files change: python3 realui/goals/buddy-gen.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "../../studio.json")))["repo"]
STATS = f"{R}/apps/main/src/app/[lang]/(app)/(stats)"
MAIN = f"{R}/apps/main/src"

# source file -> copy name (without the buddy-main- prefix)
FILES = {
    f"{MAIN}/lib/belt-colors.ts": "belt-colors",
    f"{STATS}/level/level-stats.tsx": "level-stats",
    f"{STATS}/level/level-progression.tsx": "level-progression",
    f"{STATS}/level/belt-rack.tsx": "belt-rack",
    f"{STATS}/energy/energy-stats.tsx": "energy-stats",
    f"{STATS}/energy/energy-chart.tsx": "energy-chart",
    f"{MAIN}/components/progress/progress-day-count-label.ts": "progress-day-count-label",
    f"{MAIN}/components/learn/section-page.tsx": "section-page",
    f"{MAIN}/components/learn/section-layout.tsx": "section-layout",
    f"{STATS}/_components/stats-page.tsx": "stats-page",
}

COPY_BY_SOURCE = {os.path.splitext(src)[0]: name for src, name in FILES.items()}

EXPORTS = {}
for pkg in ["learn", "ui", "utils", "core", "player"]:
    EXPORTS[pkg] = json.load(open(f"{R}/packages/{pkg}/package.json"))["exports"]


def resolve_package(spec):
    pkg, _, sub = spec[len("@zoonk/"):].partition("/")
    exports = EXPORTS[pkg]
    key = "./" + sub
    target = exports.get(key)
    if target is None:
        for pattern, value in exports.items():
            if "*" in pattern:
                prefix, suffix = pattern.split("*")
                if key.startswith(prefix) and key.endswith(suffix):
                    star = key[len(prefix):len(key) - len(suffix) or None]
                    target = value.replace("*", star) if isinstance(value, str) else value
                    break
    if isinstance(target, dict):
        target = target.get("browser") or target.get("default")
    if target is None:
        raise SystemExit(f"cannot resolve {spec}")
    return f"{R}/packages/{pkg}/{target[2:]}"


def resolve(spec, source_dir):
    if spec.startswith("@zoonk/"):
        return resolve_package(spec)
    if spec.startswith("@/"):
        base = f"{MAIN}/{spec[2:]}"
    elif spec.startswith("."):
        base = os.path.normpath(os.path.join(source_dir, spec))
    else:
        return spec
    if base in COPY_BY_SOURCE:
        return f"./buddy-main-{COPY_BY_SOURCE[base]}"
    if spec == "@/i18n/locale":
        return "./main-locale"
    if spec == "@/i18n/navigation":
        return "./main-navigation"
    for ext in [".tsx", ".ts"]:
        if os.path.exists(base + ext):
            if spec.startswith("@/"):
                text = open(base + ext).read()
                if '"@/' in text:
                    raise SystemExit(f"{spec} imports @/ itself: copy it too")
            return base + ext
    raise SystemExit(f"cannot resolve {spec} from {source_dir}")


def convert(text, source_dir):
    text = text.replace(
        'from "next-intl/server";',
        'from "next-intl";',
    )
    text = re.sub(r"\bgetExtracted\b", "useExtracted", text)
    text = re.sub(r"\bgetFormatter\b", "useFormatter", text)
    text = re.sub(r"\basync function\b", "function", text)
    text = re.sub(r"\bawait\s+", "", text)
    text = re.sub(r"Promise<([^>]+)>", r"\1", text)
    text = text.replace('import "server-only";\n', "")

    def fix(match):
        return f'{match.group(1)}"{resolve(match.group(2), source_dir)}"'

    return re.sub(r'(from |import )"([^"]+)"', fix, text)


for source, name in FILES.items():
    out = convert(open(source).read(), os.path.dirname(source))
    header = f"// Generated by buddy-gen.py from {os.path.relpath(source, R)}. Don't edit.\n"
    open(f"{HERE}/buddy-main-{name}.tsx", "w").write(header + out)
    print("wrote", name)
