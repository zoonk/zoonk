/// The outlines music notation is drawn with: the glyphs abcjs draws main's staves with (abcjs
/// 6.7.1, `src/write/creation/glyphs.js`, MIT license, Copyright (c) Paul Rosen and Gregory
/// Dyke), so a melody looks the same in the app. Units are abcjs's: a staff space is 7.75, y grows
/// down, and each glyph's origin is where it sits (a notehead's left edge on its line or space).
struct MusicGlyph: Sendable {
  /// How wide the glyph is, in abcjs units.
  let width: CGFloat
  let path: Path

  /// The outline from abcjs's commands: `M`, `m`, `l`, `c` and `z`, all but `M` relative.
  init(width: CGFloat, outline: String) {
    self.width = width
    path = Self.path(outline)
  }

  static let staffSpace: CGFloat = 7.75

  private static func path(_ outline: String) -> Path {
    var path = Path()
    var point = CGPoint.zero
    var subpathStart = CGPoint.zero
    var command: Character?
    var numbers: [CGFloat] = []
    var number = ""

    func endNumber() {
      if let value = Double(number) {
        numbers.append(CGFloat(value))
      }

      number = ""
    }

    func apply() {
      endNumber()

      switch command {
      case "M", "m":
        guard numbers.count == 2 else { break }
        point =
          command == "M"
          ? CGPoint(x: numbers[0], y: numbers[1])
          : CGPoint(x: point.x + numbers[0], y: point.y + numbers[1])
        subpathStart = point
        path.move(to: point)
      case "l":
        guard numbers.count == 2 else { break }
        point = CGPoint(x: point.x + numbers[0], y: point.y + numbers[1])
        path.addLine(to: point)
      case "c":
        guard numbers.count == 6 else { break }
        let start = point
        point = CGPoint(x: start.x + numbers[4], y: start.y + numbers[5])
        path.addCurve(
          to: point,
          control1: CGPoint(x: start.x + numbers[0], y: start.y + numbers[1]),
          control2: CGPoint(x: start.x + numbers[2], y: start.y + numbers[3]))
      case "z":
        path.closeSubpath()
        point = subpathStart
      default:
        break
      }

      numbers = []
    }

    for character in outline {
      if character.isLetter {
        apply()
        command = character
      } else if character == " " || character.isNewline {
        endNumber()
      } else if character == "-", !number.isEmpty {
        endNumber()
        number = "-"
      } else {
        number.append(character)
      }
    }

    apply()
    return path
  }
}

