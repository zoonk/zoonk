import { type TestCase } from "@/lib/types";
import { type SkillLevelsParams } from "@zoonk/ai/tasks/language/skill-levels";
import { type CefrLevel } from "@zoonk/utils/cefr";
import { type SkillLevelsExpected } from "./task";

const BANDS = {
  advanced: ["C1", "C2"],
  beginner: ["A1", "A2"],
  intermediate: ["B1", "B2"],
} as const satisfies Record<string, readonly [CefrLevel, CefrLevel]>;

/** The expected level is null where the two blind labels (Claude Opus 5.5, GPT-6.1 Sol) differed. */
type SkillRow = [
  name: string,
  description: string,
  band: keyof typeof BANDS,
  expected: CefrLevel | null,
];

function toCase({
  id,
  language,
  skills,
  targetLanguage,
}: {
  id: string;
  language: string;
  skills: SkillRow[];
  targetLanguage: string;
}): TestCase<SkillLevelsExpected, Omit<SkillLevelsParams, "model">> {
  const rows = skills.map(([name, description, band, expected], index) => ({
    expected,
    skill: { band: BANDS[band], description, id: `${id}-${index + 1}`, name },
  }));

  return {
    expected: {
      levels: Object.fromEntries(
        rows.flatMap((row) => (row.expected ? [[row.skill.id, row.expected]] : [])),
      ),
    },
    id,
    language,
    userInput: { skills: rows.map((row) => row.skill), targetLanguage },
  };
}

