private sealed interface Segment {
    data class Move(
        val x: Float,
        val y: Float,
    ) : Segment

    data class Line(
        val x: Float,
        val y: Float,
    ) : Segment

    /** [y0] is where it starts, for its extent. */
    data class Curve(
        val y0: Float,
        val x1: Float,
        val y1: Float,
        val x2: Float,
        val y2: Float,
        val x: Float,
        val y: Float,
    ) : Segment

    data object Close : Segment
}

/** abcjs's commands: `M`, `m`, `l`, `c` and `z`, all but `M` relative. */
private fun readOutline(outline: String): List<Segment> {
    val segments = mutableListOf<Segment>()
    var x = 0f
    var y = 0f
    var startX = 0f
    var startY = 0f

    Regex("([Mmlcz])([^Mmlcz]*)").findAll(outline).forEach { match ->
        val numbers =
            match.groupValues[2]
                .split(' ', '\n')
                .filter { it.isNotEmpty() }
                .map { it.toFloat() }

        when (match.groupValues[1]) {
            "M", "m" -> {
                if (match.groupValues[1] == "M") {
                    x = numbers[0]
                    y = numbers[1]
                } else {
                    x += numbers[0]
                    y += numbers[1]
                }
                startX = x
                startY = y
                segments += Segment.Move(x, y)
            }

            "l" -> {
                x += numbers[0]
                y += numbers[1]
                segments += Segment.Line(x, y)
            }

            "c" -> {
                val curve =
                    Segment.Curve(y, x + numbers[0], y + numbers[1], x + numbers[2], y + numbers[3], x + numbers[4], y + numbers[5])
                x = curve.x
                y = curve.y
                segments += curve
            }

            "z" -> {
                x = startX
                y = startY
                segments += Segment.Close
            }
        }
    }

    return segments
}

private fun outlinePath(segments: List<Segment>): Path =
    Path().apply {
        segments.forEach { segment ->
            when (segment) {
                is Segment.Move -> moveTo(segment.x, segment.y)
                is Segment.Line -> lineTo(segment.x, segment.y)
                is Segment.Curve -> cubicTo(segment.x1, segment.y1, segment.x2, segment.y2, segment.x, segment.y)
                Segment.Close -> close()
            }
        }
    }

private fun outlineBounds(segments: List<Segment>): GlyphBounds {
    val ys =
        segments.flatMap { segment ->
            when (segment) {
                is Segment.Move -> listOf(segment.y)
                is Segment.Line -> listOf(segment.y)
                is Segment.Curve -> (0..CURVE_SAMPLES).map { segment.yAt(it.toFloat() / CURVE_SAMPLES) }
                Segment.Close -> emptyList()
            }
        }

    return GlyphBounds(ys.min(), ys.max())
}

private const val CURVE_SAMPLES = 8

private fun Segment.Curve.yAt(t: Float): Float {
    val u = 1 - t
    return u * u * u * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y
}
